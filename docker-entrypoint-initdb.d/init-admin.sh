#!/usr/bin/env bash
set -euo pipefail

: "${PG_ADMIN_USER:=admin}"
: "${PG_ADMIN_PASSWORD:?PG_ADMIN_PASSWORD is required}"
: "${POSTGRES_PASSWORD:?POSTGRES_PASSWORD is required}"
: "${POSTGRES_DB:=mercurymail}"

psql -v ON_ERROR_STOP=1 --username "${POSTGRES_USER:-postgres}" --dbname "${POSTGRES_DB}" <<SQL
DO \$\$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '${PG_ADMIN_USER}') THEN
    CREATE ROLE ${PG_ADMIN_USER} WITH LOGIN SUPERUSER PASSWORD '${PG_ADMIN_PASSWORD}';
  ELSE
    ALTER ROLE ${PG_ADMIN_USER} WITH LOGIN SUPERUSER PASSWORD '${PG_ADMIN_PASSWORD}';
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'mercury') THEN
    CREATE ROLE mercury WITH LOGIN PASSWORD '${POSTGRES_PASSWORD}';
  ELSE
    ALTER ROLE mercury WITH LOGIN PASSWORD '${POSTGRES_PASSWORD}';
  END IF;
END
\$\$;

GRANT ALL PRIVILEGES ON DATABASE ${POSTGRES_DB} TO mercury;
GRANT ALL PRIVILEGES ON SCHEMA public TO mercury;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON TABLES TO mercury;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON SEQUENCES TO mercury;
SQL
